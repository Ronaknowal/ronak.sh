import fs from 'node:fs';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
const id = 'dapo-dynamic-adaptive-policy-optimization';
const dir = `docs/teaching/llm-architecture-training/${id}`;
const ledgerPath = 'docs/teaching/lesson-delivery-progress.json';
const bytes = fs.readFileSync(ledgerPath), ledger = JSON.parse(bytes), entry = ledger.topics[id];
const sha = p => createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const scopePath = 'docs/teaching/llm-architecture-training/pretraining-alignment-scope.json';
const scope = JSON.parse(fs.readFileSync(scopePath)).topics.find(t => t.id === id);
const original = `${dir}/original/dapo.jsx`, accepted = JSON.parse(fs.readFileSync(`${dir}/runtime-acceptance.json`));
assert.equal(entry.content.status, 'complete');
assert.equal(entry.implementation.status, 'in-progress');
assert.equal(scope.originalSha256, '420b6fb24ab2d641dc3d308645d5e6440ad0253191211ce456e4e0ce25592859');
assert.equal(sha(original), scope.originalSha256);
assert.equal(sha(scope.source), sha(accepted.manuscript));
assert.equal(sha(accepted.manuscript), accepted.files[accepted.manuscript]);
assert.equal(entry.content.files[scope.source], scope.originalSha256);
for (const [p, h] of Object.entries(entry.content.files)) if (p !== scope.source) assert.equal(sha(p), h, p);
const record = `${dir}/original-publication-identity.json`;
fs.writeFileSync(record, JSON.stringify({ at: new Date().toISOString(), topic: id, scope: scopePath, scopeSha256: sha(scopePath), beforeContentFiles: entry.content.files, original, originalSha256: sha(original), published: scope.source, publishedSha256: sha(scope.source), runtimeAcceptance: `${dir}/runtime-acceptance.json`, runtimeAcceptanceSha256: sha(`${dir}/runtime-acceptance.json`), explanation: 'The original archive existed with bytes equal to the frozen pre-rewrite source, but the content file map bound only its former canonical path. Completion correctly stopped before central mutation. This read-only byte comparison explicitly binds the retained archive now so guarded publication relocation can proceed. Historical acceptance packets are unchanged; no scientific or runtime check is repeated.' }, null, 2) + '\n', { flag: 'wx' });
entry.content.files[original] = sha(original);
entry.content.files[record] = sha(record);
assert.ok(fs.readFileSync(ledgerPath).equals(bytes), 'Concurrent central edit');
fs.writeFileSync(ledgerPath, JSON.stringify(ledger, null, 2) + '\n');
console.log(JSON.stringify({ boundOriginal: original, sha256: sha(original) }));
