import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const folder='docs/teaching/llm-architecture-training/fp8-training-low-precision-pre-training';
const file=`${folder}/fp8-training.jsx`, continuation=`${folder}/content-link-continuation.md`;
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const source=fs.readFileSync(file), text=source.toString('utf8');
const old='/learn/path/full-curriculum/backpropagation?module=deep-learning';
const successor='/learn/path/full-curriculum/backpropagation-automatic-differentiation?module=deep-learning-fundamentals';
assert.equal(text.split(successor).length-1,2);
assert.equal(hash(Buffer.from(text.replaceAll(successor,old))), '3b3f9772a82568af84653d1b75660e811b9e020d42016287dfe2b9ec801892bd');
assert.equal(hash(source),'3e161120c086cc5ca4635441cae9bd6f1f41ce189cb2c1c420f470a34d8fefac');
const target=fs.readFileSync('src/learn/data/topics/backprop.jsx','utf8');
assert.ok(target.includes('3. From individual numbers to tensor gradients'));
const ledgerPath='docs/teaching/lesson-delivery-progress.json', before=fs.readFileSync(ledgerPath), ledger=JSON.parse(before);
const entry=ledger.topics['fp8-training-low-precision-pre-training'];
assert.equal(entry.content.files[file],'3b3f9772a82568af84653d1b75660e811b9e020d42016287dfe2b9ec801892bd');
entry.content.files[file]=hash(source);
entry.content.files[continuation]=hash(fs.readFileSync(continuation));
const receipt=`${folder}/root-link-acceptance.json`;
fs.writeFileSync(receipt,JSON.stringify({reviewer:'root',accepted:true,scope:'Exactly two canonical prerequisite URL corrections; target heading exists. Reverse substitution reproduces accepted complete predecessor bytes. All scientific evidence conserved.',sourceHash:hash(source),continuationHash:entry.content.files[continuation]},null,2)+'\n',{flag:'wx'});
entry.content.files[receipt]=hash(fs.readFileSync(receipt));
assert.ok(fs.readFileSync(ledgerPath).equals(before));
fs.writeFileSync(ledgerPath,JSON.stringify(ledger,null,2)+'\n');
console.log('Accepted exact two-link FP8 successor; no scientific rerun or phase reset.');
