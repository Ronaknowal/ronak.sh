import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {parse} from '@babel/parser';
const sha=p=>createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const dir='docs/teaching/llm-architecture-training/grpo-rloo-kto-advanced-preference-methods';
const previous='docs/teaching/llm-architecture-training/integration/pretraining-alignment/2026-10-08T06-59-58-028Z';
const packetPath=`${dir}/metadata-successor/inputs.json`;
assert.equal(sha(packetPath),'72ae9379c3c93e136e761cad47197447ae9429ea378a964a1620fe055b4ecece');
const packet=JSON.parse(fs.readFileSync(packetPath));
for(const[p,h]of Object.entries(packet.files))assert.equal(sha(p),h,p);
const manuscript=`${dir}/manuscript.jsx`,published='src/learn/data/topics/grpo-rloo-kto.jsx';
const old=fs.readFileSync(published,'utf8'),now=fs.readFileSync(manuscript,'utf8');
const line="  readTime: '~90 min read + programs and practice',\n";
assert.equal(now.replace(line,''),old,'Only static metadata insertion is accepted');
const ast=parse(now,{sourceType:'module',plugins:['jsx']});
const lesson=ast.program.body.flatMap(x=>x.declarations||[]).find(x=>x.id.name==='lesson').init;
assert.equal(lesson.properties.find(x=>x.key.name==='readTime').value.type,'StringLiteral');
const acceptance=JSON.parse(fs.readFileSync(`${dir}/runtime-acceptance.json`));
const files={...acceptance.files,...packet.files,[packetPath]:sha(packetPath)};
files[manuscript]=sha(manuscript);
// Metadata predecessor binds the already published runtime, not the historical
// original topic. The archive in its packet preserves those exact old bytes.
delete files[published];
for(const[p,h]of Object.entries(files))assert.equal(sha(p),h,p);
const review=`${dir}/metadata-successor/root-review.md`;
fs.writeFileSync(review,`# Root different metadata closure\n\nAccepted the sole static readTime insertion after reading the complete proposed diff and metadata object, reconstructing exact predecessor bytes by deleting that line, and checking its Babel StringLiteral type. The entire learner body, scientific programs, numerical engines, controls and CSS are byte-identical to the whole runtime already reviewed. The estimate is approximate reader guidance, not a measured learning-time result. The earlier production build failed before transformation because the required field was absent; that failure remains retained. Current normal production build and opening checks still follow. No whole scientific or visual campaign was repeated for this metadata-only change.\n`,{flag:'wx'});
files[review]=sha(review);
files['scripts/accept-grouped-metadata-successor.mjs']=sha('scripts/accept-grouped-metadata-successor.mjs');
const nextAcceptance=`${dir}/runtime-metadata-acceptance.json`;
fs.writeFileSync(nextAcceptance,JSON.stringify({...acceptance,at:new Date().toISOString(),reviewer:'root; composed whole runtime and bounded metadata successor',files},null,2)+'\n',{flag:'wx'});
const previousAccepted=JSON.parse(fs.readFileSync(`${previous}/accepted-sources.json`));
for(const[p,h]of Object.entries(previousAccepted.files))if(p!==manuscript)assert.equal(sha(p),h,p);
assert.equal(sha(published),packet.files[published]);
fs.copyFileSync(manuscript,published);
const publication=JSON.parse(fs.readFileSync(`${previous}/publication.json`));
const row=publication.rows.find(r=>r.id==='grpo-rloo-kto-advanced-preference-methods');
row.acceptance=nextAcceptance;row.acceptedSha256=sha(manuscript);
const folder=`docs/teaching/llm-architecture-training/integration/pretraining-alignment/${new Date().toISOString().replace(/[:.]/g,'-')}`;
fs.mkdirSync(folder,{recursive:true});
const bound={...previousAccepted.files,...files,[published]:sha(published),[nextAcceptance]:sha(nextAcceptance)};
for(const name of ['accepted-sources.json','publication.json'])bound[`${previous}/${name}`]=sha(`${previous}/${name}`);
fs.writeFileSync(`${folder}/accepted-sources.json`,JSON.stringify({at:new Date().toISOString(),scope:previousAccepted.scope,predecessor:previous,files:bound},null,2)+'\n',{flag:'wx'});
fs.writeFileSync(`${folder}/publication.json`,JSON.stringify({...publication,at:new Date().toISOString(),predecessor:previous,note:'Sole GRPO static metadata correction accepted; all reviewed learner/runtime bodies conserved. Build and normal-reader checks pending.'},null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({accepted:true,integration:folder,guards:Object.keys(bound).length}));
