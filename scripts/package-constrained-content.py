shutil.copyfile(base/'research/iris-data.json', out/'data.json')
shutil.copyfile(base/'research/native-masks.json', out/'native-masks.json')
study = out/'study'; study.mkdir(exist_ok=True)
for file in (base/'research/iris-study').iterdir():
    if file.name.endswith('.started.json') or file.suffix not in ['.json','.py']:
        continue
    shutil.copyfile(file, study/file.name)
shutil.copyfile(base/'content-correction/evaluation-exact.json', study/'evaluation-exact.json')
shutil.copyfile(base/'content-correction/predecessor'/base/'programs/evaluate.py', study/'evaluate-original-float.py')
def sha(file):
    return hashlib.sha256(file.read_bytes()).hexdigest()
files = [p for p in out.rglob('*') if p.is_file() and p.name not in ['files.json','constrained-decoding.zip']]
manifest = {str(p.relative_to(out)).replace('\\','/'): {'sha256':sha(p),'bytes':p.stat().st_size} for p in sorted(files)}
(out/'files.json').write_text(json.dumps({'files':manifest},indent=2)+'\n',encoding='utf8')
with zipfile.ZipFile(out/'constrained-decoding.zip','w',zipfile.ZIP_DEFLATED) as archive:
    for file in sorted([*files,out/'files.json']):
        entry=zipfile.ZipInfo(str(file.relative_to(out)).replace('\\','/'),(2026,10,8,0,0,0))
        entry.compress_type=zipfile.ZIP_DEFLATED
        archive.writestr(entry,file.read_bytes())
with zipfile.ZipFile(out/'constrained-decoding.zip') as archive:
    assert archive.testzip() is None
    for name in archive.namelist():
        assert archive.read(name)==(out/name).read_bytes()
(base/'research/bundle-checks.json').write_text(json.dumps({'passed':True,'members':len(files)+1,'bundle_sha256':sha(out/'constrained-decoding.zip'),'files':manifest},indent=2)+'\n',encoding='utf8')
print(json.dumps({'members':len(files)+1,'sha256':sha(out/'constrained-decoding.zip')}))
