import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
const id='simpo-simple-preference-optimization';
const folder=`docs/teaching/llm-architecture-training/${id}`;
const sha=p=>createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const acceptance=`${folder}/content-review-acceptance.json`;
assert.equal(sha(acceptance),'a7c2a0ac87b3a3ef97d6234f2f96d9e49b3a08470034bbf88bf1adf482a1f920');
const review=JSON.parse(fs.readFileSync(acceptance));
assert.equal(review.status,'accepted-different-whole-content-review');
assert.equal(review.reviewer,'training_author');
assert.equal(review.author,'alignment_author');
assert.deepEqual(review.material_findings,[]);
const files={...review.source_bindings,...review.review_bindings,[acceptance]:sha(acceptance)};
for(const[p,h]of Object.entries(files)) assert.equal(sha(p),h,p);
const manifest=`${folder}/content-root-inputs.json`;
fs.writeFileSync(manifest,JSON.stringify({reviewer:'root',acceptedAt:new Date().toISOString(),basis:'Complete different-author source/learning review, all95 conserved author inputs,1788 complementary no-fit conditions and explicit negative-result limits. Root read the complete independent report and preparation packet; does not duplicate or relabel the different reviewer reading.',files},null,2)+'\n',{flag:'wx'});
execFileSync(process.execPath,['scripts/checkpoint-llm-pretraining-content.mjs',id,'manuscript.jsx','examples/simpo','821d477a3d4a61bd4cf93889fa001ba06b4db9ffd7ed6d7394747545de23afb9',manifest,sha(manifest)],{stdio:'inherit'});
