import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const sha=p=>createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const id='grpo-rloo-kto-advanced-preference-methods';
const dir=`docs/teaching/llm-architecture-training/${id}`;
const manuscript=`${dir}/manuscript.jsx`;
const retained=`${dir}/metadata-successor/predecessor/${manuscript}`;
const accepted=`${dir}/runtime-metadata-acceptance.json`;
const receipt=JSON.parse(fs.readFileSync(accepted));
assert.equal(receipt.accepted,true);
assert.equal(sha(manuscript),receipt.files[manuscript]);
assert.equal(fs.readFileSync(manuscript,'utf8').replace("  readTime: '~90 min read + programs and practice',\n",''),fs.readFileSync(retained,'utf8'));
const ledgerPath='docs/teaching/lesson-delivery-progress.json';
const bytes=fs.readFileSync(ledgerPath),ledger=JSON.parse(bytes),entry=ledger.topics[id];
assert.equal(entry.content.status,'complete');
assert.equal(entry.implementation.status,'in-progress');
assert.equal(entry.content.files[manuscript],sha(retained));
const before=`${dir}/metadata-successor/central-content-before.json`;
fs.writeFileSync(before,JSON.stringify(entry,null,2)+'\n',{flag:'wx'});
const report=`${dir}/metadata-successor/content-binding-relocation.json`;
fs.writeFileSync(report,JSON.stringify({at:new Date().toISOString(),accepted:true,reviewer:'root',scope:'One required static readTime field, exact reversal conserves the entire accepted original lesson body; no teaching, scientific or runtime mechanism changes.',original:{file:manuscript,sha256:sha(retained),retained},successor:{file:manuscript,sha256:sha(manuscript)},rootRuntimeAcceptance:{file:accepted,sha256:sha(accepted)},originalCentralEntry:{file:before,sha256:sha(before)},qualification:'Original frozen content and runtime acceptance packets remain unchanged historical provenance. Only the active central binding composes the explicitly accepted metadata successor; phase completion timestamp/revision retained.'},null,2)+'\n',{flag:'wx'});
entry.content.files[manuscript]=sha(manuscript);
entry.content.files[retained]=sha(retained);
entry.content.files[report]=sha(report);
entry.content.files[before]=sha(before);
assert.ok(fs.readFileSync(ledgerPath).equals(bytes),'Concurrent central edit');
fs.writeFileSync(ledgerPath,JSON.stringify(ledger,null,2)+'\n');
console.log(JSON.stringify({accepted:true,changedActiveBindings:1,bodyConserved:true}));
