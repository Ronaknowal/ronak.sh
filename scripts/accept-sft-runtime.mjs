import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const id='supervised-fine-tuning-sft';
const folder=`docs/teaching/llm-architecture-training/${id}`;
const sha=p=>createHash('sha256').update(fs.readFileSync(p)).digest('hex');
assert.equal(sha(`${folder}/runtime-inputs.json`),'bddb4d250492407ee105b64af3421367e4111f1b445ff1ec25cdcf370145d6f4');
const files={...JSON.parse(fs.readFileSync(`${folder}/runtime-inputs.json`)).bindings};
const ledger=JSON.parse(fs.readFileSync('docs/teaching/lesson-delivery-progress.json'));
assert.equal(ledger.topics[id].content.status,'complete');
Object.assign(files,ledger.topics[id].content.files);
for(const name of ['runtime-review.md','runtime-inputs.json','independent-runtime/model-checks.json','independent-runtime/browser/report.json']) files[`${folder}/${name}`]=sha(`${folder}/${name}`);
for(const p of ['scripts/review-sft-runtime-independent.mjs','scripts/review-sft-runtime-browser.cjs',...JSON.parse(fs.readFileSync(`${folder}/independent-runtime/browser/report.json`)).captures]) files[p]=sha(p);
for(const [p,h]of Object.entries(files)) assert.equal(sha(p),h,p);
const manuscript=`${folder}/lesson.jsx`;
assert.equal(sha(manuscript),'0d67202b1f8ca5e20cb2d899a558c255e1f959cf63bcfb11ffcff3d80024315e');
fs.writeFileSync(`${folder}/runtime-acceptance.json`,JSON.stringify({at:new Date().toISOString(),accepted:true,reviewer:'root',phase:'ready-for-production-integration',topic:id,manuscript,figures:'[data-sft-figure]',count:21,assets:'learn-code/supervised-fine-tuning',files,review:`${folder}/runtime-review.md`,limits:'Whole different review complete; normal production integration follows. ZIP evidence is exact HTTP bytes, not native archive-save success.'},null,2)+'\n',{flag:'wx'});
console.log(`SFT runtime accepted: ${Object.keys(files).length} exact bindings.`);
